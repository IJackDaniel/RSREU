; Практическая работа №4
; Пример №2. Мигание светодиода

start:
    ldi r16, 0x20      ; 00100000 - маска PB5
    out DDRB, r16      ; PB5 настроен на выход

    clr r17            ; Младший байт счетчика
    clr r18            ; Средний байт счетчика
    clr r19            ; Старший байт счетчика

loop:
    inc r17            ; Увеличиваем младший байт
    brne check         ; Если не 0, переходим к проверке

    inc r18            ; Переполнение: увеличиваем r18
    brne check

    inc r19            ; Увеличиваем старший байт

check:
    bst r19, 4         ; Копируем бит 4 регистра r19 в T
    brts led_on        ; Если T = 1, включаем LED

led_off:
    cbi PORTB, 5       ; Выключаем светодиод
    rjmp loop

led_on:
    sbi PORTB, 5       ; Включаем светодиод
    rjmp loop
