; Практическая работа №4. Задание №1
; Реверсивный счетчик

start:
    ldi r16, 0xFF       ; Маска для настройки порта
    out DDRD, r16       ; Все выводы PORTD - выходы

    ldi r17, 0x00       ; Начальное значение счетчика

count_up:
    out PORTD, r17      ; Выводим значение счетчика
    inc r17             ; Увеличиваем на 1
    brne count_up       ; Пока нет переполнения, продолжаем

    ldi r17, 0xFF       ; Начинаем обратный счет с 255

count_down:
    out PORTD, r17      ; Выводим значение счетчика
    dec r17             ; Уменьшаем на 1
    brne count_down     ; Пока не достигли нуля, продолжаем

    out PORTD, r17      ; Выводим 0
    rjmp count_up       ; Снова начинаем увеличение
