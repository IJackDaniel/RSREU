; Практическая работа №4. GPIO
; Пример №1: вывод чисел от 0 до 255 в PORTD

start:
    ldi r16, 0xFF     ; 255 = 11111111
    ldi r17, 0x00     ; Начальное значение счетчика
    out DDRD, r16     ; Все выводы порта D - OUTPUT

p:
    out PORTD, r17    ; Вывод текущего значения счетчика
    inc r17           ; Увеличение счетчика на 1
    rjmp p            ; Повторение цикла
