
; Практическая работа №4
; Задание №3. Уменьшение частоты мигания светодиода в 2 раза

start:
    ldi r16, 0x20
    out DDRB, r16       ; PB5 - выход

    clr r17             ; Биты 0-7 счетчика
    clr r18             ; Биты 8-15 счетчика
    clr r19             ; Биты 16-23 счетчика
    clr r20             ; Биты 24-31 счетчика

loop:
    inc r17             ; Увеличение младшего байта
    brne check          ; Если нет переполнения, к проверке

    inc r18             ; Увеличение среднего байта
    brne check

    inc r19             ; Увеличение старшего байта
    brne check

    inc r20             ; Увеличение самого старшего байта

check:
    bst r19, 5          ; Проверяем бит №21
    brts led_on         ; Если бит = 1, включаем LED

led_off:
    cbi PORTB, 5        ; Выключаем светодиод
    rjmp loop

led_on:
    sbi PORTB, 5        ; Включаем светодиод
    rjmp loop
